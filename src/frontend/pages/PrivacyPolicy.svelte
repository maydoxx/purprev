    <h2 id="security">7. How we protect your data</h2>
    <ul>
        <li>Passwords are stored only as salted hashes (argon2id, with older hashes upgraded on sign in) and can never be read back in plain text.</li>
        <li>API keys are stored only as hashes and can be scoped and revoked.</li>
        <li>Sign in, account changes and sensitive actions are rate limited, and authenticated writes require a CSRF token.</li>
        <li>Sign-up and applications go through a Cloudflare Turnstile captcha to block automated abuse.</li>
        <li>Sessions use HTTP only, same site cookies, protected by a content security policy and other security headers. Session tokens are stored only as hashes.</li>
        <li>Private messages and chat are encrypted at rest, and sign in addresses are shortened so they cannot point to a single person.</li>
        <li>Uploads are checked by content type and file signature, and XML parsing is hardened against attacks.</li>
        <li>Staff and security actions are logged, and access to user data is limited to what staff need to run and moderate the site.</li>
    </ul>
    <p>No service can promise perfect security, but we work to protect your data and we will tell you and the relevant authority about a breach where the law requires it.</p>

    <h2 id="retention">8. How long we keep it</h2>
    <p>We keep personal data only as long as we need it, then we delete or anonymise it. Security and staff logs, invite records, old usernames and decided applications are removed automatically once their period is up. The <a href="#rights">Data retention</a> control on this page lists the period for each category, and section 2 summarises it. When you delete your account we remove your account, your games, your uploads and your content, and we anonymise the few records we must keep for moderation and security so they can no longer be linked to you.</p>

