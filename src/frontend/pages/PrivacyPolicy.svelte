    <h2 id="why">3. Why we process it</h2>
    <p>We rely on a small number of legal bases:</p>
    <ul>
        <li><strong>Contract</strong> — to give you an account and the features you use (GDPR Art. 6(1)(b), PDPA Sec. 24(3)).</li>
        <li><strong>Legitimate interests</strong> — to keep the site secure, stop abuse, moderate content and keep things reliable. We balance these against your rights (GDPR Art. 6(1)(f), PDPA Sec. 24(5)).</li>
        <li><strong>Consent</strong> — for showing your social links on your profile. Each link is off unless you choose to show it, and you can turn it off again at any time (GDPR Art. 6(1)(a) and Art. 7, PDPA Sec. 19).</li>
    </ul>
    <p>We do not use your data for marketing, advertising, profiling or recommendations, and we do not sell it.</p>

    <h2 id="cookies">4. Cookies</h2>
    <p>We use strictly necessary cookies and no advertising or tracking cookies:</p>
    <ul>
        <li><strong>Session cookie</strong> — keeps you signed in. It is HTTP only, same site, and cleared when you sign out.</li>
        <li><strong>CSRF cookie</strong> — protects forms against cross site request forgery.</li>
        <li><strong>Cloudflare security cookie</strong> — set by Cloudflare when it checks that a request is genuine or when you solve the sign-up captcha. It is used for security only.</li>
    </ul>
    <p>Your theme choice is saved in your own browser, not on our servers. If we ever add optional analytics, it will only run with your consent and this page will be updated first.</p>

